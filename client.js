import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

export class SplitserError extends Error {
  constructor(message, status = 502) {
    super(message);
    this.status = status;
  }
}

const unwrap = (entry) => {
  const key = ['expense', 'income', 'payment', 'settle'].find((name) => entry?.[name]);
  return key ? { type: key, ...entry[key] } : null;
};

export class SplitserClient {
  constructor(config) {
    this.config = config;
    this.cookie = null;
    this.loginPromise = null;
    this.listCache = null;
    this.listPromise = null;
    this.transactionCache = new Map();
    this.transactionPromises = new Map();
    this.balanceCache = new Map();
    this.balancePromises = new Map();
  }

  async cookieFromDisk() {
    let contents;
    try {
      contents = await readFile(this.config.cookieFile, 'utf8');
    } catch (error) {
      if (error.code === 'ENOENT') return null;
      throw error;
    }

    for (const line of contents.split(/\r?\n/)) {
      if (!line || (line.startsWith('#') && !line.startsWith('#HttpOnly_'))) continue;
      const fields = line.replace(/^#HttpOnly_/, '').split('\t');
      if (fields.length === 7 && fields[5] === '_wbw_rails_session' &&
          Number(fields[4]) * 1000 > Date.now()) {
        return `${fields[5]}=${fields[6]}`;
      }
    }
    return null;
  }

  async login() {
    if (this.loginPromise) return this.loginPromise;
    this.loginPromise = (async () => {
      const { email, password } = this.config;
      if (!email || !password) {
        throw new SplitserError(
          'Splitser session expired. Set SPLITSER_EMAIL and SPLITSER_PASSWORD for automatic sign-in.',
          401,
        );
      }

      const response = await this.request('/api/users/sign_in', {
        method: 'POST',
        authenticated: false,
        body: JSON.stringify({ user: { email, password } }),
      });
      const values = response.headers.getSetCookie();
      const session = values.find((value) => value.startsWith('_wbw_rails_session='));
      if (!session) throw new SplitserError('Splitser sign-in returned no session cookie', 401);

      this.cookie = session.split(';', 1)[0];
      await this.saveCookies(values);
      this.listCache = null;
      this.transactionCache.clear();
      this.balanceCache.clear();
      console.log('Splitser session refreshed');
    })().finally(() => {
      this.loginPromise = null;
    });
    return this.loginPromise;
  }

  async saveCookies(values) {
    const lines = [
      '# Netscape HTTP Cookie File',
      '# Generated by splitser-sync. Contains secrets; do not commit.',
    ];
    for (const value of values) {
      const [pair, ...attributes] = value.split(';').map((part) => part.trim());
      const separator = pair.indexOf('=');
      const name = pair.slice(0, separator);
      const content = pair.slice(separator + 1);
      const options = Object.fromEntries(attributes.map((attribute) => {
        const index = attribute.indexOf('=');
        return index < 0
          ? [attribute.toLowerCase(), true]
          : [attribute.slice(0, index).toLowerCase(), attribute.slice(index + 1)];
      }));
      if (name.startsWith('__Host-') && !options.secure) continue;
      const expires = options['max-age']
        ? Math.floor(Date.now() / 1000) + Number(options['max-age'])
        : Math.floor(new Date(options.expires || Date.now() + 86400000).getTime() / 1000);
      const domain = new URL(this.config.baseUrl).hostname;
      const httpOnly = options.httponly ? '#HttpOnly_' : '';
      lines.push([httpOnly + domain, 'FALSE', options.path || '/', options.secure ? 'TRUE' : 'FALSE',
        expires, name, content].join('\t'));
    }
    await mkdir(dirname(this.config.cookieFile), { recursive: true, mode: 0o700 });
    const temporary = `${this.config.cookieFile}.${process.pid}.tmp`;
    await writeFile(temporary, lines.join('\n') + '\n', { mode: 0o600 });
    await rename(temporary, this.config.cookieFile);
  }

  async request(path, { method = 'GET', authenticated = true, body, retried = false } = {}) {
    if (authenticated && !this.cookie) this.cookie = await this.cookieFromDisk();
    if (authenticated && !this.cookie) await this.login();

    const headers = {
      Accept: 'application/json',
      'Accept-Language': 'en',
      'Accept-Version': this.config.apiVersion,
      'X-App-React': 'true',
    };
    if (body) headers['Content-Type'] = 'application/json';
    if (authenticated) headers.Cookie = this.cookie;

    let response;
    try {
      response = await fetch(new URL(path, this.config.baseUrl), {
        method, headers, body, redirect: 'manual',
        signal: AbortSignal.timeout(this.config.timeoutMs),
      });
    } catch (error) {
      throw new SplitserError(`Could not reach Splitser: ${error.message}`);
    }

    if (response.status === 401 || response.status === 403 ||
        (response.status >= 300 && response.status < 400)) {
      await response.arrayBuffer();
      if (!authenticated) throw new SplitserError('Splitser rejected the email or password', 401);
      if (retried) throw new SplitserError('Splitser rejected the refreshed session', 401);
      this.cookie = null;
      await this.login();
      return this.request(path, { method, authenticated, body, retried: true });
    }
    if (!response.ok) {
      await response.arrayBuffer();
      throw new SplitserError(`Splitser returned HTTP ${response.status}`);
    }
    return response;
  }

  async json(path, options) {
    const response = await this.request(path, options);
    try {
      return await response.json();
    } catch {
      throw new SplitserError('Splitser returned invalid JSON');
    }
  }

  async lists({ refresh = false } = {}) {
    if (!refresh && this.listCache && this.listCache.expires > Date.now()) {
      return this.listCache.value;
    }
    if (this.listPromise) return this.listPromise;
    this.listPromise = (async () => {
      const body = await this.page('/api/lists', { 'filter[archived]': 'false' });
      this.listCache = { value: body, expires: Date.now() + this.config.listTtlMs };
      return body;
    })().finally(() => {
      this.listPromise = null;
    });
    return this.listPromise;
  }

  async page(path, filters = {}) {
    const data = [];
    let page = 0;
    let metadata;
    do {
      const url = new URL(path, this.config.baseUrl);
      url.searchParams.set('page', String(page));
      url.searchParams.set('per_page', '100');
      for (const [key, value] of Object.entries(filters)) url.searchParams.set(key, value);
      const body = await this.json(url.pathname + url.search);
      if (!Array.isArray(body.data)) throw new SplitserError(`Invalid collection from ${path}`);
      data.push(...body.data);
      metadata = body;
      page += 1;
    } while (metadata.pagination && page < metadata.pagination.total_pages);
    return { ...metadata, data };
  }

  // Net balances are one request per list; no transaction export is needed for reconciliation.
  async balances({ listId, refresh = false } = {}) {
    const lists = await this.lists({ refresh });
    const selected = listId ? lists.data.filter((entry) => entry.list?.id === listId) : lists.data;
    if (listId && selected.length === 0) throw new SplitserError('Active Splitser list not found', 404);

    const result = await Promise.all(selected.map(async ({ list }) => {
      const cached = this.balanceCache.get(list.id);
      const version = Math.max(list.modified_at || 0, list.updated_at || 0);
      if (!refresh && cached && cached.version === version && cached.expires > Date.now()) {
        return { ...cached.value, cached: true };
      }
      if (this.balancePromises.has(list.id)) return this.balancePromises.get(list.id);

      const promise = (async () => {
        const body = await this.json(`/api/lists/${list.id}/balance`);
        if (!Array.isArray(body.balance?.member_totals)) {
          throw new SplitserError(`Invalid balance for Splitser list ${list.id}`);
        }
        const value = { list, data: body.balance.member_totals.map((entry) => entry.member_total), cached: false };
        this.balanceCache.set(list.id, {
          value, version, expires: Date.now() + this.config.transactionTtlMs,
        });
        return value;
      })().finally(() => this.balancePromises.delete(list.id));
      this.balancePromises.set(list.id, promise);
      return promise;
    }));

    return {
      data: result,
      meta: { lists: result.length, cachedLists: result.filter((entry) => entry.cached).length },
    };
  }

  async transactions({ listId, refresh = false } = {}) {
    const lists = await this.lists({ refresh });
    const selected = listId ? lists.data.filter((entry) => entry.list?.id === listId) : lists.data;
    if (listId && selected.length === 0) throw new SplitserError('Active Splitser list not found', 404);

    const result = await Promise.all(selected.map(async (entry) => {
      const list = entry.list;
      const cached = this.transactionCache.get(list.id);
      const version = Math.max(list.modified_at || 0, list.updated_at || 0);
      if (!refresh && cached && cached.version === version && cached.expires > Date.now()) {
        return { ...cached.value, cached: true };
      }
      if (this.transactionPromises.has(list.id)) return this.transactionPromises.get(list.id);

      const promise = (async () => {
        const [items, settlements] = await Promise.all([
          this.page(`/api/lists/${list.id}/list_items`),
          this.page(`/api/lists/${list.id}/settles`),
        ]);
        const seen = new Set();
        const transactions = [...items.data, ...settlements.data].map(unwrap).filter((item) => {
          if (!item || seen.has(`${item.type}:${item.id}`)) return false;
          seen.add(`${item.type}:${item.id}`);
          return true;
        });
        const value = { list, data: transactions, fetchedAt: new Date().toISOString(), cached: false };
        this.transactionCache.set(list.id, {
          value, version, expires: Date.now() + this.config.transactionTtlMs,
        });
        return value;
      })().finally(() => {
        this.transactionPromises.delete(list.id);
      });
      this.transactionPromises.set(list.id, promise);
      return promise;
    }));

    return {
      data: result,
      meta: {
        lists: result.length,
        transactions: result.reduce((total, entry) => total + entry.data.length, 0),
        cachedLists: result.filter((entry) => entry.cached).length,
      },
    };
  }
}
